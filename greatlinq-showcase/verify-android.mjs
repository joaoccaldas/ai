import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
const files=['index.html','app.js','model.js','styles.css','mark.svg','pump.svg','fallback-world.svg','VISITOR-NOTE.txt'];
for(const name of files) assert.ok(readFileSync(name).length>0,`Missing web asset: ${name}`);
const gradle=readFileSync('android/app/build.gradle','utf8');
assert.match(gradle,/stageShowcaseAssets/);
assert.match(gradle,/sourceSets.main.assets.srcDirs/);
for(const name of files) assert.ok(gradle.includes(`'${name}'`),`Android bundle excludes ${name}`);
const xml=readFileSync('android/app/src/main/AndroidManifest.xml','utf8');
assert.match(xml,/android\.permission\.INTERNET/);
assert.doesNotMatch(xml,/READ_EXTERNAL_STORAGE|WRITE_EXTERNAL_STORAGE|CAMERA|RECORD_AUDIO|ACCESS_FINE_LOCATION|ACCESS_COARSE_LOCATION/);
assert.match(xml,/android:usesCleartextTraffic="false"/);
assert.match(xml,/android:allowBackup="false"/);
const java=readFileSync('android/app/src/main/java/ai/ond/spatialshowcase/MainActivity.java','utf8');
assert.match(java,/WebViewAssetLoader/);
assert.match(java,/settings\.setAllowFileAccess\(false\)/);
assert.match(java,/settings\.setJavaScriptCanOpenWindowsAutomatically\(false\)/);
assert.match(java,/"joaoccaldas\.github\.io"\.equals\(uri\.getHost\(\)\)/);
assert.match(java,/startActivity\(new Intent\(Intent\.ACTION_VIEW, uri\)\)/);
assert.doesNotMatch(java,/addJavascriptInterface|onPermissionRequest/);
for(const name of ['app.js','model.js']) execFileSync('node',['--check',name],{stdio:'inherit'});
console.log(JSON.stringify({pass:true,assets:files.length,permission:'INTERNET only',offlineShell:true,externalLinks:'user-click only',privateData:'not included'},null,2));